#!/usr/bin/env python3
"""
sync_repl_docs.py - Refresh the vendored Browser REPL method reference.

The agent's only tool is the Kernel Browser REPL. Its tool description embeds the
method reference that kernel-images generates into server/docs/repl.md. This script
pulls the latest copy of that generated section into core/repl_reference.md.

Usage:
    uv run python -m scripts.sync_repl_docs
    uv run python -m scripts.sync_repl_docs --ref <git-sha-or-branch>
    uv run python -m scripts.sync_repl_docs --include-webmcp
"""

from __future__ import annotations

import argparse
import json
import urllib.request
from pathlib import Path

REPO = "kernel/kernel-images"
DOC_PATH = "server/docs/repl.md"
BEGIN_MARKER = "<!-- BEGIN GENERATED REPL METHOD REFERENCE -->"
END_MARKER = "<!-- END GENERATED REPL METHOD REFERENCE -->"
WEBMCP_HEADING = "### WebMCP methods"
OUTPUT = Path(__file__).resolve().parent.parent / "core" / "repl_reference.md"


def resolve_sha(ref: str) -> str:
    with urllib.request.urlopen(f"https://api.github.com/repos/{REPO}/commits/{ref}") as resp:
        return json.load(resp)["sha"]


def fetch_reference(sha: str, include_webmcp: bool) -> str:
    url = f"https://raw.githubusercontent.com/{REPO}/{sha}/{DOC_PATH}"
    with urllib.request.urlopen(url) as resp:
        doc = resp.read().decode()

    start = doc.index(BEGIN_MARKER) + len(BEGIN_MARKER)
    end = doc.index(END_MARKER)
    reference = doc[start:end].strip()

    if not include_webmcp and WEBMCP_HEADING in reference:
        reference = reference[: reference.index(WEBMCP_HEADING)].strip()

    return reference


def main() -> None:
    parser = argparse.ArgumentParser(description="Refresh core/repl_reference.md")
    parser.add_argument("--ref", default="main", help="kernel-images git ref (default: main)")
    parser.add_argument(
        "--include-webmcp",
        action="store_true",
        help="Keep the WebMCP methods section (omitted by default to keep the prompt small)",
    )
    args = parser.parse_args()

    sha = resolve_sha(args.ref)
    reference = fetch_reference(sha, args.include_webmcp)
    header = f"<!-- Generated by scripts/sync_repl_docs.py from {REPO}@{sha}:{DOC_PATH} -->\n\n"
    OUTPUT.write_text(header + reference + "\n")
    print(f"Wrote {OUTPUT} ({len(reference)} chars) from {REPO}@{sha[:12]}")


if __name__ == "__main__":
    main()
